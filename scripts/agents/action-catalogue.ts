/**
 * Writes server/agents/action-catalogue.generated.ts: for every action type the game's type table (src/types/actions.ts) describes, its one-line
 * description (the first sentence of the comment above it) and the shape of its payload, as the type is written. `list_action_types` serves it.
 * A test checks that every action type the registry dispatches is in it, so a new action cannot be left out.
 *
 *   node --experimental-strip-types scripts/agents/action-catalogue.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const rows: [string, string, string][] = []
const seen = new Set<string>()
for (const file of ['src/types/actions.ts', 'src/types/campus.ts', 'src/types/stories.ts']) {
  const lines = readFileSync(join(root, file), 'utf8').split('\n')
  let comment = '', open = false
  for (let n = 0; n < lines.length; n += 1) {
    const line = lines[n] ?? ''
    // A comment, of one line or several: the text above the entry that follows.
    if (/^\s*\/\*\*/.test(line)) { comment = ''; open = true }
    if (open) { comment += ` ${line.replace(/^\s*\/?\*+\/?\s?/, '').replace(/\*\/\s*$/, '')}`; if (/\*\//.test(line)) open = false; continue }
    const one = /^\s{2}(?:'([a-z][\w.-]*)'|([a-z][\w-]*)): \{ payload: (.*?); ok:/.exec(line)
    const many = /^\s{2}(?:'([a-z][\w.-]*)'|([a-z][\w-]*)): \{\s*$/.exec(line)
    const entry = one ?? many
    if (entry) {
      const type = entry[1] ?? entry[2] ?? ''
      let payload = one ? entry[3] ?? '{}' : ''
      if (many) for (let m = n + 1; m < Math.min(lines.length, n + 6); m += 1) { const found = /^\s+payload: (.*)$/.exec(lines[m] ?? ''); if (found) { payload = found[1] ?? ''; break; } }
      const first = comment.replace(/SERVER ONLY:.*/, '').replace(/\s+/g, ' ').trim().split(/(?<=[.!?])\s/)[0] ?? ''
      if (!seen.has(type) && payload) { seen.add(type); rows.push([type, first.slice(0, 200), payload.replace(/\s+/g, ' ').slice(0, 240)]) }
      comment = ''
    } else if (line.trim() !== '' && !/^\s*\/\//.test(line)) comment = ''
  }
}
const text = `// GENERATED by scripts/agents/action-catalogue.ts from src/types/actions.ts. Do not edit.\n/** [action type, one-line description, payload type as written]. */\nexport const ACTION_CATALOGUE: readonly (readonly [string, string, string])[] = ${JSON.stringify(rows, null, 1).replace(/\n\s+/g, ' ').replace(/\], \[/g, '],\n  [').replace(/^\[ /, '[\n  ').replace(/ \]$/, '\n]')}\n`
writeFileSync(join(root, 'server/agents/action-catalogue.generated.ts'), text)
console.log(`${rows.length} action types written`)
