// Content versions for the model files: `/assets/` is served as immutable for a year, but a pack file keeps its name when it is
// prepared again, so every URL a game loads carries `?v=<first 10 hex of the file's SHA-256>` and a changed file is a new URL.
//
//   node --experimental-strip-types scripts/assets/versions.ts [--check]
//
// Writes src/arena/asset-versions.generated.ts: a map from each .glb under public/assets/packs/ (as the site serves it) to its
// version. `--check` writes nothing and exits 1 when the file on disk is not what the models say (the prebuild runs it, and
// scripts/assets/versions.test.ts checks it too). scripts/assets/prepare.ts runs the write after it prepares a pack.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const VERSIONS_FILE = join(repo, 'src', 'arena', 'asset-versions.generated.ts')
export const VERSION_LENGTH = 10

export const versionOf = (bytes: Uint8Array): string => createHash('sha256').update(bytes).digest('hex').slice(0, VERSION_LENGTH)

/** Every .glb under the packs folder as `/assets/packs/<pack>/<file>` -> version, sorted by name. */
export function readVersions(root = repo): Record<string, string> {
  const packs = join(root, 'public', 'assets', 'packs'), out: Record<string, string> = {}
  for (const pack of readdirSync(packs, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    for (const file of readdirSync(join(packs, pack)).filter((f) => f.endsWith('.glb')).sort()) out[`/assets/packs/${pack}/${file}`] = versionOf(readFileSync(join(packs, pack, file)))
  }
  return out
}

/** The text of the generated file. */
export function renderVersions(versions: Record<string, string>): string {
  const lines = Object.entries(versions).map(([path, v]) => `  '${path}': '${v}',`)
  return `// Generated by scripts/assets/versions.ts from the files in public/assets/packs/. Do not edit.\nexport const ASSET_VERSIONS: Readonly<Record<string, string>> = Object.freeze({\n${lines.join('\n')}\n})\n`
}

export const writeVersions = (): void => writeFileSync(VERSIONS_FILE, renderVersions(readVersions()))

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  if (process.argv.includes('--check')) {
    let have = ''
    try { have = readFileSync(VERSIONS_FILE, 'utf8') } catch { /* missing */ }
    if (have !== renderVersions(readVersions())) { console.error('src/arena/asset-versions.generated.ts is out of date: run npm run assets:versions'); process.exit(1) }
  } else writeVersions()
}
