import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FIRST_LENGTH, PACKED, WORD_COUNTS } from '../src/words/data/dictionary.ts'
import { MAX_DICTIONARY_ASSET_BYTES, type DictionaryAssetManifest } from '../src/words/dictionary-asset.ts'

export interface BuildDictionaryAssetOptions { readonly outDir: string; readonly typescriptPath?: string }

export async function buildDictionaryAsset(options: BuildDictionaryAssetOptions): Promise<DictionaryAssetManifest> {
  const bytes = Buffer.from(PACKED, 'utf8')
  if (!bytes.length || bytes.length > MAX_DICTIONARY_ASSET_BYTES) throw new Error(`Dictionary asset is ${bytes.length} bytes (limit ${MAX_DICTIONARY_ASSET_BYTES})`)
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const file = `dictionary.${sha256}.txt`
  const manifest: DictionaryAssetManifest = { path: `/assets/words/${file}`, sha256, bytes: bytes.length, firstLength: FIRST_LENGTH, wordCounts: WORD_COUNTS }
  await mkdir(resolve(options.outDir), { recursive: true })
  await writeChanged(join(resolve(options.outDir), file), bytes)
  if (options.typescriptPath) {
    const path = resolve(options.typescriptPath)
    await mkdir(dirname(path), { recursive: true })
    await writeChanged(path, `// Generated by scripts/build-dictionary-asset.ts. Do not edit.\nimport type { DictionaryAssetManifest } from './dictionary-asset.ts'\n\nexport const DICTIONARY_ASSET = Object.freeze(${JSON.stringify(manifest)} satisfies DictionaryAssetManifest)\n`)
  }
  return manifest
}

async function writeChanged(path: string, value: string | Uint8Array): Promise<void> {
  const bytes = typeof value === 'string' ? Buffer.from(value) : Buffer.from(value)
  try { if ((await readFile(path)).equals(bytes)) return }
  catch (error) { if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error }
  await writeFile(path, bytes)
}

function argument(name: string): string | undefined {
  const index = process.argv.indexOf(name)
  return index < 0 ? undefined : process.argv[index + 1]
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = argument('--out')
  if (!outDir) throw new Error('Usage: build-dictionary-asset.ts --out <directory> [--typescript <file>]')
  const manifest = await buildDictionaryAsset({ outDir, typescriptPath: argument('--typescript') })
  console.log(`Dictionary asset generated: ${manifest.bytes} bytes.`)
}
