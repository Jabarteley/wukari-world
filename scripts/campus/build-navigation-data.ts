import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { CAMPUS_NAVIGATION_DATA } from '../../src/campus/unilag/navigation-data-source.ts'

const args = process.argv.slice(2)
const check = args.includes('--check')
const at = args.indexOf('--typescript')
const target = resolve(at < 0 ? 'src/campus/unilag/navigation-data.generated.ts' : args[at + 1] || '')
const source = `// Generated by scripts/campus/build-navigation-data.ts. Do not edit.\nimport type { CampusNavigationData } from './navigation-data.ts'\n\nexport const CAMPUS_NAVIGATION_DATA: CampusNavigationData = ${JSON.stringify(CAMPUS_NAVIGATION_DATA)}\n`

if (check) assert.equal(await readFile(target, 'utf8'), source, 'campus navigation data differs; run campus:navigation')
else await writeFile(target, source)
console.log(`Campus navigation data ${check ? 'passed' : 'generated'}: ${Buffer.byteLength(source)} bytes.`)
