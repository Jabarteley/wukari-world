import { createHash } from 'node:crypto'
import { existsSync } from 'node:fs'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { CITY_CONTENT_ASSET_VERSION, MAX_CITY_CONTENT_ASSET_BYTES, type CityContentAsset, type CityContentAssetManifestRow } from '../../src/game/cities/content-asset.ts'
import { GENERATED_CITY_CATALOGUE_ROWS } from '../../src/game/cities/catalogue.generated.ts'
import type { CityModule } from '../../src/types/content.ts'

export interface BuildCityContentAssetsOptions {
  readonly root?: string
  readonly outDir: string
  readonly manifestPath?: string
  readonly typescriptPath?: string
}

export interface BuiltCityContentAssets {
  readonly rows: readonly CityContentAssetManifestRow[]
  readonly payloads: ReadonlyMap<string, CityContentAsset>
}

const record = (value: unknown): value is Record<string, unknown> => value !== null && typeof value === 'object' && !Array.isArray(value)
const cityModule = (value: unknown): value is CityModule => record(value) && typeof value.id === 'string' && record(value.rules)
  && value.rules.id === value.id && typeof value.loadContent === 'function' && typeof value.loadMap === 'function'

/** Source-order JSON which refuses every value JSON.stringify would silently alter or discard. Object key order is gameplay-visible through Object.values. */
export function canonicalCityJson(value: unknown): string {
  const encode = (item: unknown, at: string): string => {
    if (item === null) return 'null'
    if (typeof item === 'string' || typeof item === 'boolean') return JSON.stringify(item)
    if (typeof item === 'number') {
      if (!Number.isFinite(item)) throw new TypeError(`Non-finite number at ${at}`)
      return Object.is(item, -0) ? '0' : JSON.stringify(item)
    }
    if (Array.isArray(item)) return `[${item.map((entry, index) => encode(entry, `${at}[${index}]`)).join(',')}]`
    if (!record(item) || Object.getPrototypeOf(item) !== Object.prototype && Object.getPrototypeOf(item) !== null) throw new TypeError(`Non-JSON value at ${at}`)
    const keys = Object.keys(item)
    return `{${keys.map(key => {
      const entry = item[key]
      if (entry === undefined || typeof entry === 'function' || typeof entry === 'symbol' || typeof entry === 'bigint') throw new TypeError(`Lossy JSON value at ${at}.${key}`)
      return `${JSON.stringify(key)}:${encode(entry, `${at}.${key}`)}`
    }).join(',')}}`
  }
  return encode(value, '$')
}

async function authoredCities(root: string): Promise<CityModule[]> {
  const citiesDir = join(root, 'src/game/cities')
  const folders = (await readdir(citiesDir, { withFileTypes: true }))
    .filter(entry => entry.isDirectory() && existsSync(join(citiesDir, entry.name, 'index.ts')))
    .map(entry => entry.name)
  const modules = new Map<string, CityModule>()
  for (const folder of folders) {
    const namespace: unknown = await import(pathToFileURL(join(citiesDir, folder, 'index.ts')).href)
    if (!record(namespace)) throw new Error(`${folder}/index.ts did not export a module namespace`)
    const found = Object.values(namespace).find((value): value is CityModule => cityModule(value) && value.id === folder)
    if (!found) throw new Error(`${folder}/index.ts must export one CityModule whose id matches its folder`)
    modules.set(found.id, found)
  }
  const ordered = GENERATED_CITY_CATALOGUE_ROWS.map(([id]) => {
    const module = modules.get(id)
    if (!module) throw new Error(`Generated city catalogue names missing authored city ${id}`)
    modules.delete(id)
    return module
  })
  if (modules.size) throw new Error(`Authored cities are absent from the generated catalogue: ${[...modules.keys()].join(', ')}`)
  return ordered
}

const manifestJson = (rows: readonly CityContentAssetManifestRow[]): string => `${canonicalCityJson({ version: CITY_CONTENT_ASSET_VERSION, cities: rows })}\n`
const typescriptRows = (rows: readonly CityContentAssetManifestRow[]): string => `// Generated by scripts/city/build-content-assets.ts. Do not edit.\nimport type { CityContentAssetManifestRow } from './content-asset.ts'\n\nexport const CITY_CONTENT_ASSETS = Object.freeze(${canonicalCityJson(rows)} satisfies readonly CityContentAssetManifestRow[])\n`

export async function buildCityContentAssets(options: BuildCityContentAssetsOptions): Promise<BuiltCityContentAssets> {
  const root = resolve(options.root ?? dirname(fileURLToPath(new URL('../../package.json', import.meta.url))))
  const outDir = resolve(options.outDir)
  const modules = await authoredCities(root)
  const rows: CityContentAssetManifestRow[] = []
  const payloads = new Map<string, CityContentAsset>()
  await mkdir(outDir, { recursive: true })
  for (const module of modules) {
    const content = await module.loadContent()
    const payload: CityContentAsset = { version: CITY_CONTENT_ASSET_VERSION, cityId: module.id, rules: module.rules, content }
    const json = canonicalCityJson(payload)
    const bytes = Buffer.byteLength(json)
    if (bytes > MAX_CITY_CONTENT_ASSET_BYTES) throw new Error(`City content asset ${module.id} is ${bytes} bytes (limit ${MAX_CITY_CONTENT_ASSET_BYTES})`)
    const sha256 = createHash('sha256').update(json).digest('hex')
    const file = `${module.id}.${sha256}.json`
    await writeChanged(join(outDir, file), json)
    rows.push({ id: module.id, path: `/assets/cities/${file}`, sha256, bytes })
    payloads.set(module.id, payload)
  }
  if (options.manifestPath) { await mkdir(dirname(resolve(options.manifestPath)), { recursive: true }); await writeChanged(resolve(options.manifestPath), manifestJson(rows)) }
  if (options.typescriptPath) { await mkdir(dirname(resolve(options.typescriptPath)), { recursive: true }); await writeChanged(resolve(options.typescriptPath), typescriptRows(rows)) }
  return { rows: Object.freeze(rows), payloads }
}

async function writeChanged(path: string, value: string | Uint8Array): Promise<void> {
  const bytes = typeof value === 'string' ? Buffer.from(value) : Buffer.from(value)
  try { if ((await readFile(path)).equals(bytes)) return }
  catch (error) { if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error }
  await writeFile(path, bytes)
}

function argument(name: string): string | undefined {
  const index = process.argv.indexOf(name)
  return index < 0 ? undefined : process.argv[index + 1]
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = argument('--out')
  if (!outDir) throw new Error('Usage: build-content-assets.ts --out <directory> [--manifest <file>] [--typescript <file>]')
  const result = await buildCityContentAssets({ outDir, manifestPath: argument('--manifest'), typescriptPath: argument('--typescript') })
  console.log(`City content assets generated for ${result.rows.length} cities.`)
}
