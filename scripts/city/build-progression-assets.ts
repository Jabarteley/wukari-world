import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { basename, join, resolve } from 'node:path'
import { createSourceProgressionSnapshot } from '../../src/game/progression/source-provider.ts'
import { MAX_PROGRESSION_ASSET_BYTES } from '../../src/game/progression/provider.ts'
import type { ProgressionAsset, ProgressionAssetManifestRow } from '../../src/game/progression/asset.ts'

const args = process.argv.slice(2), check = args.includes('--check')
const option = (name: string, fallback: string): string => { const at = args.indexOf(name); return at < 0 ? fallback : resolve(args[at + 1] || '') }
const out = option('--out', 'dist/assets/progression')
const typescript = option('--typescript', 'src/game/progression/assets.generated.ts')
const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex')
const snapshot = createSourceProgressionSnapshot()
const assets: ProgressionAsset[] = []
const limit = 4_500_000
let items: typeof snapshot.episodes = [], order = 0
const flush = (): void => { if (items.length) { assets.push({ version: 1, kind: 'episodes', order: order++, items }); items = [] } }
for (const episode of snapshot.episodes) {
  const next = [...items, episode]
  if (Buffer.byteLength(JSON.stringify({ version: 1, kind: 'episodes', order, items: next })) > limit) flush()
  items = [...items, episode]
}
flush()
assets.push({ version: 1, kind: 'journeys', order: 0, items: snapshot.journeys,
  acceptedCityIds: snapshot.acceptedCityIds, acceptedCountryIds: snapshot.acceptedCountryIds })
assets.push({ version: 1, kind: 'missions', order: 0, value: snapshot.missions })

const rows: ProgressionAssetManifestRow[] = [], files = new Map<string, string>()
for (const asset of assets) {
  const text = JSON.stringify(asset), bytes = Buffer.byteLength(text)
  assert.ok(bytes > 0 && bytes <= MAX_PROGRESSION_ASSET_BYTES, `${asset.kind} asset is ${bytes} bytes`)
  const hash = sha256(text), stem = asset.kind === 'episodes' ? `episodes-${asset.order}` : asset.kind
  const file = `${stem}.${hash}.json`, count = asset.kind === 'missions' ? asset.value.definitions.length : asset.items.length
  rows.push({ kind: asset.kind, order: asset.order, path: `/assets/progression/${file}`, sha256: hash, bytes, count })
  files.set(file, text)
}
const source = `// Generated by scripts/city/build-progression-assets.ts. Do not edit.\nimport type { ProgressionAssetManifestRow } from './asset.ts'\n\nexport const PROGRESSION_CONTENT_ASSETS = Object.freeze(${JSON.stringify(rows)} satisfies readonly ProgressionAssetManifestRow[])\n`
if (check) {
  assert.equal(await readFile(typescript, 'utf8'), source, 'progression asset manifest differs; run progression:assets')
  console.log(`Progression asset manifest passed: ${rows.length} files, ${snapshot.episodes.length} episodes, ${snapshot.journeys.length} journeys.`)
} else {
  await rm(out, { recursive: true, force: true }); await mkdir(out, { recursive: true }); await mkdir(resolve(typescript, '..'), { recursive: true })
  await Promise.all([...files].map(([file, text]) => writeFile(join(out, basename(file)), text)))
  await writeFile(typescript, source)
  console.log(`Progression assets: ${rows.map(row => `${row.kind}[${row.order}]=${row.bytes}`).join(', ')}`)
}
