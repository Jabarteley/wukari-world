import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { loadCityContent, loadCityRules, playableCityIds, loadCityNetwork, cityCatalogue } from '../../src/game/cities/index.ts'
import { RESERVED_CITIES } from '../../src/game/cities/catalogue.ts'
import type { WorldStorySeed, WorldStoryActivity } from '../../src/types/world-progression.ts'

const GENERATED = new URL('../../src/game/content/world-progression.generated.ts', import.meta.url)
const COVERAGE = new URL('../../docs/research/worldwide-progression-2026-10-15/coverage.json', import.meta.url)
const check = process.argv.includes('--check')

const sha256 = (value: string | Uint8Array): string => createHash('sha256').update(value).digest('hex')
const readText = (url: URL): Promise<string> => readFile(url, 'utf8')
const generatedSource = (seeds: readonly WorldStorySeed[]): string =>
  `// Generated by scripts/city/build-progression-content.ts. Do not edit by hand.\nimport type { WorldStorySeed } from '../../types/world-progression.ts'\n\nexport const WORLD_STORY_SEEDS: readonly WorldStorySeed[] = Object.freeze(${JSON.stringify(seeds, null, 2)} satisfies readonly WorldStorySeed[])\n`

const eligibilityProblems = (activity: Record<string, unknown>): string[] => {
  const problems: string[] = []
  for (const key of Object.keys(activity)) if (key.startsWith('requires') && activity[key] !== undefined && activity[key] !== false) problems.push(key)
  for (const key of ['consumes', 'minimumNeeds', 'hours', 'choices', 'careerTrack', 'unavailable', 'where']) if (activity[key] !== undefined && activity[key] !== false) problems.push(key)
  if (typeof activity.duration !== 'number' || !Number.isFinite(activity.duration) || activity.duration <= 0) problems.push('duration')
  if (activity.cost !== undefined && activity.cost !== 0) problems.push('cost')
  return problems
}

const venueScore = (venue: { id: string; kind: string; definition: { category: string; hours?: unknown } }): number => {
  if (venue.definition.hours) return -100
  const prefer: Record<string, number> = {
    park: 30, buka: 26, market: 24, unilag: 23, library: 22, university: 21,
    museum: 19, walk: 18, shrine: 16, beach: 15, office: 14, viewing: 12,
    hub: -8, airport: -12,
  }
  return prefer[venue.kind] ?? (venue.definition.category === 'care' ? 0 : 5)
}

await loadCityNetwork()
const ids = [...playableCityIds()]
const catalogue = cityCatalogue()
const openCatalogue = catalogue.filter((city) => city.open)
const closedCatalogue = catalogue.filter((city) => !city.open)
const effectiveReserved = RESERVED_CITIES.filter((city) => !ids.includes(city.id))
const seeds: WorldStorySeed[] = []
const sourceRows: Record<string, { moduleSha256: string; contentEntrySha256: string; seedSha256: string }> = {}
const countryIds = new Set<string>()

for (const cityId of ids) {
  const rules = await loadCityRules(cityId)
  const content = await loadCityContent(cityId)
  const countryId = rules.country.id === 'nigeria' ? 'ng' : rules.country.id
  countryIds.add(countryId)
  if (rules.status !== 'open') throw new Error(`${cityId}: playable id has non-open rules status ${rules.status}`)
  if (content.cityId !== cityId) throw new Error(`${cityId}: content belongs to ${content.cityId}`)

  const venues = new Map(content.venues.filter((venue) => venue.id !== 'home').map((venue) => [venue.id, venue]))
  const regulars = content.regulars.filter((regular) => venues.has(regular.venueId))
  const hosts = regulars.flatMap((regular) => {
    const venue = venues.get(regular.venueId)
    if (!venue || venue.definition.hours) return []
    return [{ regular, venue, score: venueScore(venue) }]
  }).sort((a, b) => b.score - a.score || a.venue.id.localeCompare(b.venue.id) || a.regular.id.localeCompare(b.regular.id))
  const hostChoice = hosts[0]
  if (!hostChoice) throw new Error(`${cityId}: no regular at an always-open public venue`)

  const candidates = content.venues.flatMap((venue) => {
    if (venue.id === 'home' || venue.definition.hours) return []
    return Object.values(venue.definition.spots).flatMap((spot) => spot.activities.flatMap((activity) => {
      if (eligibilityProblems(activity as unknown as Record<string, unknown>).length) return []
      if (venue.definition.category === 'care' || venue.kind === 'hospital' || venue.kind === 'worship') return []
      return [{ venue, spot, activity, score: venueScore(venue) }]
    }))
  }).sort((a, b) => b.score - a.score || a.venue.id.localeCompare(b.venue.id) || a.spot.id.localeCompare(b.spot.id) || a.activity.id.localeCompare(b.activity.id))

  const practicalCandidate = candidates.find((candidate) => candidate.venue.id !== hostChoice.venue.id)
    ?? candidates[0]
  if (!practicalCandidate) throw new Error(`${cityId}: no unconditional free activity at an always-open public venue`)
  const discoveryCandidate = candidates.find((candidate) => candidate.venue.id !== practicalCandidate.venue.id
    && candidate.activity.id !== practicalCandidate.activity.id)
  if (!discoveryCandidate) throw new Error(`${cityId}: fewer than two distinct unconditional free public activities`)

  const toActivity = (candidate: typeof practicalCandidate): WorldStoryActivity => ({
    venue: candidate.venue.id,
    venueName: candidate.venue.name,
    spot: candidate.spot.id,
    id: candidate.activity.id,
    label: candidate.activity.label,
  })
  const guide = content.thingsToDo.find((place) => place.venueId === discoveryCandidate.venue.id)
  const seed: WorldStorySeed = {
    cityId,
    cityName: rules.name,
    countryId,
    countryName: rules.country.name,
    host: {
      id: hostChoice.regular.id,
      name: hostChoice.regular.definition.name,
      venue: hostChoice.venue.id,
      venueName: hostChoice.venue.name,
    },
    practical: toActivity(practicalCandidate),
    discovery: toActivity(discoveryCandidate),
    placeLine: guide?.line ?? discoveryCandidate.venue.whatYouCanDo,
  }
  seeds.push(seed)

  const moduleBytes = await readText(new URL(`../../src/game/cities/${cityId}/index.ts`, import.meta.url))
  const contentBytes = await readText(new URL(`../../src/game/cities/${cityId}/content.ts`, import.meta.url))
  sourceRows[cityId] = {
    moduleSha256: sha256(moduleBytes),
    contentEntrySha256: sha256(contentBytes),
    seedSha256: sha256(JSON.stringify(seed)),
  }
}

const seedIds = seeds.map((seed) => seed.cityId)
assert.equal(new Set(seedIds).size, seeds.length, 'city seeds must be unique')
assert.deepEqual([...seedIds].sort(), [...ids].sort(), 'there must be exactly one seed per playable city')
for (const seed of seeds) {
  const rules = await loadCityRules(seed.cityId)
  const content = await loadCityContent(seed.cityId)
  assert.equal(seed.countryId, rules.country.id === 'nigeria' ? 'ng' : rules.country.id)
  assert.ok(content.regulars.some((regular) => regular.id === seed.host.id && regular.venueId === seed.host.venue))
  for (const item of [seed.practical, seed.discovery]) {
    const venue = content.venues.find((candidate) => candidate.id === item.venue)
    assert.ok(venue && venue.id !== 'home' && venue.name === item.venueName)
    const spot = venue.definition.spots[item.spot]
    assert.ok(spot?.activities.some((activity) => activity.id === item.id && activity.label === item.label
      && activity.duration > 0 && (activity.cost ?? 0) === 0 && eligibilityProblems(activity as unknown as Record<string, unknown>).length === 0))
  }
}

const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: new URL('../../', import.meta.url), encoding: 'utf8' }).trim()
const coverage = {
  schemaVersion: 1,
  generatedBy: 'scripts/city/build-progression-content.ts',
  sourceHead: head,
  counts: {
    playableCityIds: ids.length,
    openCatalogueCities: openCatalogue.length,
    loadableCityModules: ids.length,
    loadableCityContents: seeds.length,
    reservedClosedCities: closedCatalogue.length,
    reservedClosedCityIds: closedCatalogue.map((city) => city.id).sort(),
    declaredReservedCityIds: RESERVED_CITIES.map((city) => city.id).sort(),
    effectiveReservedExclusions: effectiveReserved.map((city) => city.id).sort(),
    authoritativeCountryIds: countryIds.size,
  },
  identityNote: 'Country IDs come from each loaded CityModule.rules.country.id; nigeria is normalized to ng. The generated landing figure is independently derived by scripts/city/build-catalogue.ts from those same rule IDs.',
  reservedNote: 'Only IDs outside playableCityIds are excluded. RESERVED_CITIES currently declares kaduna, but the generated city index contains kaduna as open, so it is not excluded; there are no closed catalogue cities in this source revision.',
  fictionNote: 'Host names and roles are fictional game regulars from city content. Place names and activity wording are copied from existing game content; seeds make no claims about real residents, service availability, history, or schedules.',
  sourceHashes: sourceRows,
  cities: seeds.map((seed) => ({
    cityId: seed.cityId,
    cityName: seed.cityName,
    countryId: seed.countryId,
    countryName: seed.countryName,
    host: seed.host,
    practical: seed.practical,
    discovery: seed.discovery,
    placeLine: seed.placeLine,
    sourceHashes: sourceRows[seed.cityId],
  })),
}
const coverageText = `${JSON.stringify(coverage, null, 2)}\n`
const sourceText = generatedSource(seeds)

if (check) {
  const [existingSource, existingCoverage] = await Promise.all([readText(GENERATED), readText(COVERAGE)])
  assert.equal(existingSource, sourceText, 'generated source differs; run the generator to update it')
  const archived = JSON.parse(existingCoverage) as Record<string, unknown>
  assert.deepEqual({ ...archived, sourceHead: head }, coverage, 'coverage differs; run the generator to update it')
  console.log(`Progression content check passed: ${seeds.length} cities, ${countryIds.size} authoritative country IDs.`)
} else {
  await mkdir(new URL('../../docs/research/worldwide-progression-2026-10-15/', import.meta.url), { recursive: true })
  await Promise.all([writeFile(GENERATED, sourceText), writeFile(COVERAGE, coverageText)])
  console.log(`Generated progression content for ${seeds.length} cities in ${countryIds.size} authoritative country IDs.`)
}
