import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import {createStationFrame} from '../../../src/game/cities/stations/frame.ts';
import {createStationBuildings} from '../../../src/game/cities/stations/buildings.ts';
const [artifact,reviewFile,out]=process.argv.slice(2);
if(!artifact||!reviewFile||!out)throw Error('Expected geometry artifact, station review and output directory');
const file=join(artifact,'station-geometry.json'),raw=readFileSync(file),source=JSON.parse(raw),review=JSON.parse(readFileSync(reviewFile));
assert.equal(createHash('sha256').update(raw).digest('hex'),review.geometryArtifactSha256);
assert.equal(source.sourceSha256,review.sourceSha256);
const station=review.candidates.find(c=>c.id==='rothera');
const eligible=station.buildings.filter(b=>b.membership==='inside'&&!b.sourceDispute);
assert.equal(eligible.length,7);
const features=new Map(source.features.map(f=>[f.ref,f]));
const buildings=eligible.map(b=>{
 const f=features.get(b.ref);assert.ok(f.complete&&f.closedByNodeIdentity);
 const levels=Number(f.tags['building:levels']);
 const metres=Number.isFinite(levels)&&levels>0&&levels<=10?levels*3:4;
 return {id:f.ref,name:b.name,ring:f.points.map(([lon,lat])=>({lon,lat})),height:{metres,kind:'estimated'},colour:/^#[0-9a-f]{6}$/i.test(f.tags['building:colour']??'')?f.tags['building:colour']:'#aab9c5'};
});
const frame=createStationFrame({lon:-68.1248,lat:-67.568889});
const built=createStationBuildings(frame,buildings);
built.geometry.computeBoundingBox();
const pos=built.geometry.getAttribute('position');
assert.ok(pos&&Array.from(pos.array).every(Number.isFinite));
assert.ok(built.triangles>0&&built.triangles<10000);
assert.ok(built.geometry.boundingBox.max.y<=.061&&built.geometry.boundingBox.min.y>=-1e-7);
assert.throws(()=>createStationBuildings(frame,[{...buildings[0],height:{metres:0,kind:'estimated'}}]));
assert.throws(()=>createStationBuildings(frame,[{...buildings[0],ring:buildings[0].ring.slice(0,-1)}]));
mkdirSync(out,{recursive:true});
writeFileSync(join(out,'station-buildings.geometry.json'),JSON.stringify(built.geometry.toJSON()));
writeFileSync(join(out,'station-building-proof.json'),JSON.stringify({sourceGitSHA:process.env.GITHUB_SHA,sourceSha256:source.sourceSha256,geometryArtifactSha256:review.geometryArtifactSha256,station:'rothera',buildings:buildings.map(({ring,...b})=>b),triangles:built.triangles,vertices:pos.count,meshCount:1,heightPolicy:'3m per mapped level; otherwise4m. All heights estimated, not surveyed.',invalidHeightRejected:true,openRingRejected:true,status:'GEOMETRY_CANDIDATE',limitations:['No current-operation or gameplay-service claims.','No registration/nativebrowser/release acceptance.']},null,2));
built.geometry.dispose();
console.log(JSON.stringify({buildings:buildings.length,triangles:built.triangles,status:'GEOMETRY_CANDIDATE'}));
