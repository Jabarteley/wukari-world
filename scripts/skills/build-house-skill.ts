// The generated parts of the house skill (public/skills/allworld-house/): the house description reference and the limits from the game's
// own code, the bundled model check, and the file index. `--check` verifies without writing; src/spaces/house-skill.test.ts runs it in CI.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'
import { EXAMPLE_SPEC, HOUSE_SPEC, ROOFS, WALLS } from '../../src/spaces/house-spec.ts'
import { GLB_EXTENSIONS, GLB_LIMITS, HOUSE_GLB_LIMITS } from '../../src/spaces/glb.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
export const SKILL_DIR = 'public/skills/allworld-house'

function houseSpecMd(): string {
  return `# The house description (generated from src/spaces/house-spec.ts)

JSON. Metres. **x** runs across the front of the house from its left end (0) to its right end (width); **z** runs from the front wall
(0) to the back wall (depth); floors count from 0 (the ground floor). The front wall faces the street.

| Field | What |
|---|---|
| \`v\` | always 1 |
| \`name\` | optional, at most ${HOUSE_SPEC.name} letters, generic ("Our house") |
| \`storeys\` | 1 to ${HOUSE_SPEC.storeys} |
| \`width\`, \`depth\` | the outside size, ${HOUSE_SPEC.width[0]} to ${HOUSE_SPEC.width[1]} m |
| \`storeyHeight\` | floor to floor, ${HOUSE_SPEC.storeyHeight[0]} to ${HOUSE_SPEC.storeyHeight[1]} m (3 if unsure) |
| \`walls\` | \`{ color, inner?, trim? }\`: outside, inside and window-frame colours as \`#rrggbb\` |
| \`roof\` | \`{ shape, color, pitch? }\`: shape ${ROOFS.map((r) => `\`${r}\``).join(', ')}; pitch in degrees (10 to 50) for a gable or hip roof |
| \`rooms\` | up to ${HOUSE_SPEC.rooms}: \`{ name, floor, x, z, w, d, floorColor? }\`, a rectangle on its floor; inner walls are drawn along every room edge inside the house |
| \`doors\` | up to ${HOUSE_SPEC.doors}: \`{ floor, wall, at? , x?, z?, width, height?, main?, color? }\` |
| \`windows\` | up to ${HOUSE_SPEC.windows}: \`{ floor, wall, at, width, height?, sill? }\` |
| \`stairs\` | up to ${HOUSE_SPEC.stairs}: \`{ floor, x, z, w, d, up }\`: a flight from \`floor\` to the one above, rising towards \`up\` (\`x\`, \`-x\`, \`z\`, \`-z\`) |
| \`extras\` | \`{ porch?, fence?, gate?, balcony? }\` |

**Walls of a door or window:** ${WALLS.map((w) => `\`${w}\``).join(', ')}. On an outside wall, \`at\` is the middle of the opening in metres
along the wall: front and back walls from x = 0, left and right walls from z = 0. On an \`inner\` wall, \`x\` and \`z\` are the middle of
the doorway, on a room edge. Mark the front door \`"main": true\`; it is where visitors come in. Doors are 2.1 m high unless you say;
windows 1.2 m high from a 0.9 m sill.

The game fixes small mistakes (sizes past the house, a missing front door) and says what it changed. It refuses only what cannot be a house.

## Worked example

\`\`\`json
${JSON.stringify(EXAMPLE_SPEC, null, 2)}
\`\`\`
`
}

function limitsMd(): string {
  const row = (label: string, a: number, b: number) => `| ${label} | ${a.toLocaleString('en')} | ${b.toLocaleString('en')} |`
  return `# The game's limits for a .glb (generated from src/spaces/glb.ts)

| | A model | A whole house (\`--house\`) |
|---|---|---|
${row('Megabytes', GLB_LIMITS.bytes / 1e6, HOUSE_GLB_LIMITS.bytes / 1e6)}
${row('Triangles', GLB_LIMITS.triangles, HOUSE_GLB_LIMITS.triangles)}
${row('Pictures', GLB_LIMITS.textures, HOUSE_GLB_LIMITS.textures)}
${row('Picture side, pixels', GLB_LIMITS.texturePx, HOUSE_GLB_LIMITS.texturePx)}
${row('Parts (nodes)', GLB_LIMITS.nodes, HOUSE_GLB_LIMITS.nodes)}
${row('Meshes', GLB_LIMITS.meshes, HOUSE_GLB_LIMITS.meshes)}
${row('Materials', GLB_LIMITS.materials, HOUSE_GLB_LIMITS.materials)}

glTF 2.0 binary only, every buffer and picture inside the file. Pictures PNG, JPEG or WebP. Extensions a model may use:
${[...GLB_EXTENSIONS].sort().map((e) => `\`${e}\``).join(', ')}. Never Draco, never KTX2.

A player keeps one whole house and up to 30 models (300 MB in all). \`node scripts/check_model.mjs file.glb [--house]\` runs the same check.
`
}

function checkModel(): string {
  const out = buildSync({ entryPoints: [join(root, 'scripts/skills/check-model-entry.ts')], bundle: true, platform: 'node', format: 'esm', target: 'node18', write: false, legalComments: 'none', minify: false })
  return `#!/usr/bin/env node\n// Allworld's model check, bundled from src/spaces/glb.ts (AGPL-3.0-or-later). Generated by scripts/skills/build-house-skill.ts: do not edit.\n${out.outputFiles[0]!.text}`
}

export const FILES = ['SKILL.md', 'reference/photos.md', 'reference/house-spec.md', 'reference/limits.md', 'reference/blender.md', 'reference/privacy.md', 'reference/worlds.md', 'scripts/build_house.py', 'scripts/project_photos.py', 'scripts/check_model.mjs', 'scripts/upload.mjs'] as const

export function generated(): Record<string, string> {
  return {
    [`${SKILL_DIR}/reference/house-spec.md`]: houseSpecMd(),
    [`${SKILL_DIR}/reference/limits.md`]: limitsMd(),
    [`${SKILL_DIR}/scripts/check_model.mjs`]: checkModel(),
    [`${SKILL_DIR}/index.json`]: `${JSON.stringify({ name: 'allworld-house', files: FILES }, null, 2)}\n`,
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const [path, content] of Object.entries(generated())) {
    const full = join(root, path)
    let had = ''
    try { had = readFileSync(full, 'utf8') } catch { /* new */ }
    if (had === content) continue
    stale++
    if (check) console.error(`${path} is stale`)
    else writeFileSync(full, content)
  }
  if (check && stale) process.exit(1)
  console.log(check ? 'The house skill is current.' : `Wrote ${stale} file(s).`)
}
