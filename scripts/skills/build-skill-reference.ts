// Writes the reference files of the Allworld skill for Claude (skills/allworld-spaces/reference/) from the game's own source, so they
// never drift: the furniture catalogue, the house style options and the plots of every house size and of a group room.
//
//   node --experimental-strip-types scripts/skills/build-skill-reference.ts           write the files
//   node --experimental-strip-types scripts/skills/build-skill-reference.ts --check   exit 1 when a committed file is stale
//
// scripts/skills/build-skill-reference.test.ts fails when a committed file differs from skillReference().
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FURNITURE } from '../../src/game/content/furniture.ts'
import { HOUSE_STYLE, HOUSE_TIERS, STYLE_FIELDS, TIER_ORDER } from '../../src/game/content/world.ts'
import { describePlot, roomPlot, tierPlot } from '../../src/spaces/plan.ts'

export const REFERENCE_DIR = 'skills/allworld-spaces/reference'
const naira = (n: number): string => `₦${n.toLocaleString('en-GB')}`
const banner = (file: string): string => `<!-- Generated by scripts/skills/build-skill-reference.ts from the game source (${file}). Do not edit by hand: run \`node --experimental-strip-types scripts/skills/build-skill-reference.ts\`. -->\n`

function catalogue(): string {
  const rows = Object.values(FURNITURE).map((f) => `| ${f.id} | ${f.label} | ${f.w}×${f.h} | ${f.wall ? 'yes' : 'no'} | ${naira(f.price)} | ${f.kind} | ${f.category} |`)
  return `${banner('src/game/content/furniture.ts')}\n# Furniture catalogue\n\nEvery piece a plan may use. Use the id exactly. Size is width×height in tiles before rotation. A wall piece hangs on a wall.\n\n| id | label | size | wall | price | kind | category |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`
}

function houseStyle(): string {
  const parts = STYLE_FIELDS.map((field) => {
    const options = HOUSE_STYLE[field].map((o, i) => `- ${i}: ${o.label}${o.price ? ` (${naira(o.price)})` : ''}`)
    return `## ${field}\n\n${options.join('\n')}`
  })
  return `${banner('src/game/content/world.ts')}\n# House style\n\nIn a plan, \`style\` is an object of indexes, for example \`{ "wall": 2, "roof": 0 }\`. A field you leave out keeps the house's own look. A price is charged when a field changes to that option. A group room has no style.\n\n${parts.join('\n\n')}\n`
}

function plots(): string {
  const parts = TIER_ORDER.map((tier) => `## ${tier}: ${HOUSE_TIERS[tier].label}\n\n${describePlot(tierPlot(tier)).map((l) => `- ${l}`).join('\n')}`)
  parts.push(`## room: group room\n\n${describePlot(roomPlot()).map((l) => `- ${l}`).join('\n')}`)
  return `${banner('src/spaces/plan.ts')}\n# Plots\n\nThe grid of every house size and of a group room. Use \`target: "home"\` with a \`tier\`, or \`target: "room"\`.\n\n${parts.join('\n\n')}\n`
}

/** Path (from the repository root) → content of every generated file. */
export function skillReference(): Record<string, string> {
  return {
    [`${REFERENCE_DIR}/catalogue.md`]: catalogue(),
    [`${REFERENCE_DIR}/house-style.md`]: houseStyle(),
    [`${REFERENCE_DIR}/plots.md`]: plots(),
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
  const files = skillReference()
  if (process.argv.includes('--check')) {
    const stale = Object.keys(files).find((path) => !existsSync(join(root, path)) || readFileSync(join(root, path), 'utf8') !== files[path])
    if (stale) { console.error(`${stale} is stale: run node --experimental-strip-types scripts/skills/build-skill-reference.ts`); process.exit(1) }
  } else {
    for (const [path, content] of Object.entries(files)) { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), content) }
  }
}
